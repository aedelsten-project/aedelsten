"""Writes src/eri/src/batch/kernels.rs: straight-line Rust for the two-electron integrals of the small classes in the
McMurchie-Davidson form (L. E. McMurchie and E. R. Davidson, J. Comput. Phys. 26, 218 (1978)),

    (ab|cd)[c_ab, c_cd] = sum_(tuv, tau nu phi) E_ab[c_ab, tuv] pref (-1)^(tau + nu + phi) R^0_(t+tau, u+nu, v+phi) E_cd[tau nu phi, c_cd]

factored as the batches use it: X = R E_cd summed over the ket's primitives for one bra primitive, then E_ab X once.

    python3 tools/generate_ere_kernels.py L_UNROLL > src/eri/src/batch/kernels.rs

re_<lab>_<lcd>, one per l_ab + l_cd <= L_UNROLL: X[tuv, c_cd] += (ADD) or = pref sum_(tau nu phi) (-1)^(tau + nu + phi) R E_cd, the R
values from the Boys values (the lets of generate_r_kernels.py), unrolled over the Hermite functions of both sides, a
loop over the ket components. ebra_<lab>: out[:, m] += sum_tuv X[tuv, m] E_ab[:, tuv], by `generated::ebra_tiled` with
the bra's Hermite functions as its compile-time size. `dispatch` calls the batch driver with the kernels of
`(l_ab, l_cd)` as function items, so that each class is compiled with them inlined; `re_kernels` gives the `re_*` of
`(l_ab, l_cd)` as function pointers (the ERI gradient's ket step, at the bra's order raised by one). The ket's work is per primitive
quartet and the bra's per bra primitive, so the pair with fewer components belongs in the ket: the walks sort the
pairs so (`EriData`). The components are runtime lengths: the Hermite coefficients carry the normalization and any
Cartesian-to-spherical transform.

Layouts, column-major: E_ab (n_ab, tuv_ab) per primitive product (the bra side, `mmd_transpose_in`), E_cd
(tuv_cd, n_cd) per primitive product (the ket side as stored), X (tuv_ab, columns), out (n_ab, columns).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from generate_r_kernels import Kernel, hermite_order  # noqa: E402


def re(lab, lcd):
    kernel = Kernel()
    bra, ket = hermite_order(lab), hermite_order(lcd)
    # The R matrix scaled and signed, one column per ket Hermite function: pref (-1)^(tau + nu + phi) R.
    columns = []
    for (tau, nu, phi) in ket:
        scale = 'm_pref' if (tau + nu + phi) % 2 else 'pref'
        columns.append('[' + ', '.join(f'{scale} * {kernel.need(0, t + tau, u + nu, v + phi)}' for (t, u, v) in bra) + ']')
    return '\n'.join([
        f'/// `X += R E_cd` (`ADD`) or `X = R E_cd` for `l_ab = {lab}`, `l_cd = {lcd}`: {len(bra)} x {len(ket)} Hermite functions.',
        '#[inline(always)]',
        f'pub(crate) fn re_{lab}_{lcd}<const ADD: bool>(boys: &[f64], pcx: f64, pcy: f64, pcz: f64, pref: f64, e_cd: &[f64], x: &mut [f64]) {{',
        f'    let boys = &boys[..{lab + lcd + 1}];',
        *kernel.lines,
        '    let m_pref = -pref;',
        f'    let r: [[f64; {len(bra)}]; {len(ket)}] = [',
        *[f'        {c},' for c in columns],
        '    ];',
        '    apply_r::<ADD, _, _>(&r, e_cd, x);',
        '}',
        ''])


def ebra(lab):
    n = len(hermite_order(lab))
    return '\n'.join([
        f'/// `out += E_ab X` for `l_ab = {lab}`: {n} Hermite functions, `n_ab` components, as many columns as `x` and `out` hold.',
        '#[inline(always)]',
        f'pub(crate) fn ebra_{lab}(e_ab: &[f64], n_ab: usize, x: &[f64], out: &mut [f64]) {{',
        f'    super::generated::ebra_tiled::<{n}>(e_ab, n_ab, x, out);',
        '}',
        ''])


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    l_unroll = int(sys.argv[1])
    pairs = [(lab, lcd) for lab in range(l_unroll + 1) for lcd in range(l_unroll + 1 - lab)]
    # REUSE-IgnoreStart (the generated file's header, not this file's)
    out = [
        '// SPDX-FileCopyrightText: 2026 Ernst D. Larsson',
        '// SPDX-License-Identifier: MIT',
        # REUSE-IgnoreEnd
        '',
        f'// Generated by `python3 tools/generate_ere_kernels.py {l_unroll}`; do not edit.',
        '',
        '//! Straight-line two-electron integrals of the classes with `l_ab + l_cd <= L_UNROLL`: `re_*` (`R E_cd` of one',
        '//! primitive quartet) and `ebra_*` (`E_ab X` of one bra primitive), and `dispatch`, the batch driver with them',
        '//! inlined; the classes above go through the BLAS tiles of the general path.',
        '',
        '#![allow(clippy::all, unused_variables)]',
        '',
        'use arrays::scratch::{Arena, ArenaError};',
        'use basis::contraction::ShellKind;',
        'use basis::shell_pairs::ShellPair;',
        'use mmd::hermite_coulomb_integrals::RangeVersion;',
        '',
        '/// The highest `l_ab + l_cd` with kernels.',
        f'pub(crate) const L_UNROLL: usize = {l_unroll};',
        '',
        '/// The batch `(pair_ab|pair_cd)` by `generated::batch_generated` with the kernels of `(l_ab, l_cd)`; `None`',
        '/// above `L_UNROLL`.',
        "#[allow(clippy::too_many_arguments)]",
        "pub(crate) fn dispatch<'a, R: RangeVersion, Sab: ShellKind, Scd: ShellKind>(",
        '    lab: usize,',
        '    lcd: usize,',
        '    pair_ab: &ShellPair<Sab>,',
        '    pair_cd: &ShellPair<Scd>,',
        '    bra: &[f64],',
        '    ket: &[f64],',
        "    arena: &mut Arena<'a>,",
        '    omega: f64,',
        ") -> Option<Result<&'a mut [f64], ArenaError>> {",
        '    use super::generated::batch_generated as batch;',
        '    Some(match (lab, lcd) {',
        *[f'        ({lab}, {lcd}) => batch::<R, Sab, Scd, _, _, _>(pair_ab, pair_cd, bra, ket, arena, omega, re_{lab}_{lcd}::<true>, re_{lab}_{lcd}::<false>, ebra_{lab}),'
          for lab, lcd in pairs],
        '        _ => return None,',
        '    })',
        '}',
        '',
        '/// A `re_*` kernel: `(boys, P - Q along x, y, z, prefactor, E_cd, X)`.',
        'pub(crate) type ReKernel = fn(&[f64], f64, f64, f64, f64, &[f64], &mut [f64]);',
        '',
        '/// The `re_*` kernels of `(l_ab, l_cd)`, summing into `X` and setting it; `None` above `L_UNROLL`.',
        'pub(crate) fn re_kernels(lab: usize, lcd: usize) -> Option<(ReKernel, ReKernel)> {',
        '    Some(match (lab, lcd) {',
        *[f'        ({lab}, {lcd}) => (re_{lab}_{lcd}::<true>, re_{lab}_{lcd}::<false>),' for lab, lcd in pairs],
        '        _ => return None,',
        '    })',
        '}',
        '',
    ]
    out += [
        '/// `X[:, c] (+)= R E_cd[:, c]` for every ket component `c`, `R` the signed, scaled R matrix (`TAB x TCD`, column',
        '/// per ket Hermite function): a matrix-vector product per column of compile-time size, vectorized over the bra.',
        '#[inline(always)]',
        'fn apply_r<const ADD: bool, const TAB: usize, const TCD: usize>(r: &[[f64; TAB]; TCD], e_cd: &[f64], x: &mut [f64]) {',
        '    for (x, e) in x.chunks_exact_mut(TAB).zip(e_cd.chunks_exact(TCD)) {',
        '        let mut acc = [0.0; TAB];',
        '        for (column, &e) in r.iter().zip(e) {',
        '            for (a, &c) in acc.iter_mut().zip(column) {',
        '                *a += c * e;',
        '            }',
        '        }',
        '        for (x, a) in x.iter_mut().zip(acc) {',
        '            if ADD { *x += a } else { *x = a }',
        '        }',
        '    }',
        '}',
        '',
    ]
    out += [re(lab, lcd) for lab, lcd in pairs]
    out += [ebra(lab) for lab in range(l_unroll + 1)]
    sys.stdout.write('\n'.join(out).rstrip('\n') + '\n')


if __name__ == '__main__':
    main()
