"""Writes src/mmd/src/hermite_r_generated.rs: straight-line Rust for the McMurchie-Davidson Hermite Coulomb integrals
(L. E. McMurchie and E. R. Davidson, J. Comput. Phys. 26, 218 (1978)).

    python3 tools/generate_r_kernels.py TENSOR_L_MAX MATRIX_L_MAX > src/mmd/src/hermite_r_generated.rs

r_tensor_<L>: R^0_tuv, t + u + v <= L, packed in hermite_index order (v slowest, t fastest), for L <= TENSOR_L_MAX.
r_matrix_<lab>_<lcd>: the bra x ket R matrix of the general ERI path, column by column, element
(tuv, tau nu phi) = pref (-1)^(tau + nu + phi) R^0_(t + tau, u + nu, v + phi), for lab, lcd <= MATRIX_L_MAX.
Both take boys[n] = R^n_000 for n = 0..=L (the operator enters only through them) and (pcx, pcy, pcz) = P - Q.

The recursion R^n_(t+1)uv = t R^(n+1)_(t-1)uv + X R^(n+1)_tuv (likewise u with Y, v with Z), reduced in t first, then u,
then v; every R^n_tuv a kernel needs is written once, as a let, after what it reads.
"""
import sys

AXES = ('pcx', 'pcy', 'pcz')


def hermite_order(l):
    """(t, u, v) with t + u + v <= l in hermite_index order: v slowest, then u, t fastest."""
    return [(t, u, v) for v in range(l + 1) for u in range(l + 1 - v) for t in range(l + 1 - v - u)]


class Kernel:
    """The lets of one kernel: each R^n_tuv once, after the values it reads."""

    def __init__(self):
        self.lines, self.done = [], set()

    def need(self, n, t, u, v):
        """The expression of R^n_tuv, writing its let (and those it reads) first if not yet written."""
        if (t, u, v) == (0, 0, 0):
            return f'boys[{n}]'
        name = f'r{n}_{t}_{u}_{v}'
        if (n, t, u, v) in self.done:
            return name
        index = [t, u, v]
        axis = next(i for i in range(3) if index[i] > 0)
        m = index[axis] - 1
        lower = list(index)
        lower[axis] = m
        term = f'{AXES[axis]} * {self.need(n + 1, *lower)}'
        if m > 0:
            lower[axis] = m - 1
            term += f' + {float(m)!r} * {self.need(n + 1, *lower)}'
        self.lines.append(f'    let {name} = {term};')
        self.done.add((n, t, u, v))
        return name


def r_tensor(l):
    kernel = Kernel()
    values = [kernel.need(0, *tuv) for tuv in hermite_order(l)]
    return '\n'.join([
        f'/// `R^0_tuv`, `t + u + v <= {l}`, into `out` in `hermite_index` order.',
        '#[inline(always)]',
        f'pub fn r_tensor_{l}(boys: &[f64], pcx: f64, pcy: f64, pcz: f64, out: &mut [f64]) {{',
        f'    let boys = &boys[..{l + 1}];',
        f'    let out = &mut out[..{len(values)}];',
        *kernel.lines,
        *[f'    out[{i}] = {value};' for i, value in enumerate(values)],
        '}',
        ''])


def r_matrix(lab, lcd):
    kernel = Kernel()
    bra, ket = hermite_order(lab), hermite_order(lcd)
    columns = []
    for (tau, nu, phi) in ket:
        sign = 'pref' if (tau + nu + phi) % 2 == 0 else 'mref'
        columns.append('    {')
        columns.append(f'        let c = &mut columns.next().expect("one column per ket Hermite function")[..{len(bra)}];')
        for i, (t, u, v) in enumerate(bra):
            columns.append(f'        c[{i}] = {sign} * {kernel.need(0, t + tau, u + nu, v + phi)};')
        columns.append('    }')
    return '\n'.join([
        f'/// The bra x ket R matrix of `l_ab = {lab}`, `l_cd = {lcd}`: {len(bra)} x {len(ket)}, one column per ket Hermite function in',
        '/// `hermite_index` order, the signs and `pref` included.',
        '#[inline(always)]',
        f"pub fn r_matrix_{lab}_{lcd}<'c>(boys: &[f64], pcx: f64, pcy: f64, pcz: f64, pref: f64, mut columns: impl Iterator<Item = &'c mut [f64]>) {{",
        f'    let boys = &boys[..{lab + lcd + 1}];',
        '    let mref = -pref;',
        *kernel.lines,
        *columns,
        '}',
        ''])


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    tensor_l_max, matrix_l_max = int(sys.argv[1]), int(sys.argv[2])
    pairs = [(lab, lcd) for lab in range(matrix_l_max + 1) for lcd in range(matrix_l_max + 1)]
    # REUSE-IgnoreStart (the generated file's header, not this file's)
    out = [
        '// SPDX-FileCopyrightText: 2026 Ernst D. Larsson',
        '// SPDX-License-Identifier: MIT',
        # REUSE-IgnoreEnd
        '',
        f'// Generated by `python3 tools/generate_r_kernels.py {tensor_l_max} {matrix_l_max}`; do not edit.',
        '',
        '//! Straight-line Hermite Coulomb integrals (McMurchie-Davidson): `r_tensor` for `l <= R_TENSOR_L_MAX`, `r_matrix`',
        '//! for `l_ab, l_cd <= R_MATRIX_L_MAX`; above them the recursion (`hermite_r_tensor_rolling`) and its gather.',
        '',
        '// The lowest kernels read no P - Q, and those without odd ket terms no negated prefactor.',
        '#![allow(clippy::all, unused_variables)]',
        '',
        '/// The highest `l` of `r_tensor`.',
        f'pub const R_TENSOR_L_MAX: usize = {tensor_l_max};',
        '/// The highest `l_ab` and `l_cd` of `r_matrix`.',
        f'pub const R_MATRIX_L_MAX: usize = {matrix_l_max};',
        '',
        '/// `R^0_tuv`, `t + u + v <= l`, into `out` in `hermite_index` order; false (nothing written) for `l` above',
        '/// `R_TENSOR_L_MAX`.',
        '#[inline(always)]',
        'pub fn r_tensor(l: usize, boys: &[f64], pcx: f64, pcy: f64, pcz: f64, out: &mut [f64]) -> bool {',
        '    match l {',
        *[f'        {l} => r_tensor_{l}(boys, pcx, pcy, pcz, out),' for l in range(tensor_l_max + 1)],
        '        _ => return false,',
        '    }',
        '    true',
        '}',
        '',
        '/// The bra x ket R matrix of `(l_ab, l_cd)` into `columns`; false (nothing written) above `R_MATRIX_L_MAX`.',
        '#[inline(always)]',
        "pub fn r_matrix<'c>(lab: usize, lcd: usize, boys: &[f64], pcx: f64, pcy: f64, pcz: f64, pref: f64, columns: impl Iterator<Item = &'c mut [f64]>) -> bool {",
        '    match (lab, lcd) {',
        *[f'        ({lab}, {lcd}) => r_matrix_{lab}_{lcd}(boys, pcx, pcy, pcz, pref, columns),' for lab, lcd in pairs],
        '        _ => return false,',
        '    }',
        '    true',
        '}',
        '',
    ]
    out += [r_tensor(l) for l in range(tensor_l_max + 1)]
    out += [r_matrix(lab, lcd) for lab, lcd in pairs]
    sys.stdout.write('\n'.join(out).rstrip('\n') + '\n')


if __name__ == '__main__':
    main()
